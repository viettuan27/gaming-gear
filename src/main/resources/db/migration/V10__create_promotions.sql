CREATE TABLE cms_promotions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(150) NOT NULL,
 slug VARCHAR(200) NOT NULL UNIQUE,
 excerpt VARCHAR(500), content TEXT NOT NULL,
 cover_image_object_key VARCHAR(500), meta_title VARCHAR(160), meta_description VARCHAR(300),
 status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
 published_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE cms_promotion_products (
 promotion_id BIGINT NOT NULL REFERENCES cms_promotions(id) ON DELETE CASCADE,
 product_id BIGINT NOT NULL REFERENCES products(id), PRIMARY KEY (promotion_id, product_id)
);
CREATE TABLE cms_promotion_categories (
 promotion_id BIGINT NOT NULL REFERENCES cms_promotions(id) ON DELETE CASCADE,
 category_id BIGINT NOT NULL REFERENCES categories(id), PRIMARY KEY (promotion_id, category_id)
);
CREATE INDEX idx_cms_promotions_public ON cms_promotions (status, published_at DESC, id DESC);
